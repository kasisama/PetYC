package admin

import (
	"bytes"
	"testing"
)

func TestValidateImageUploadAcceptsPNGContent(t *testing.T) {
	// 1×1 transparent PNG
	png := []byte{0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x06, 0x00, 0x00, 0x00, 0x1f, 0x15, 0xc4, 0x89, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x44, 0x41, 0x54, 0x08, 0xd7, 0x63, 0xf8, 0xcf, 0xc0, 0xf0, 0x1f, 0x00, 0x05, 0x00, 0x01, 0xff, 0x89, 0x99, 0x3d, 0x1d, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82}

	ext, err := validateImageUpload(bytes.NewReader(png))
	if err != nil {
		t.Fatalf("validateImageUpload() error = %v", err)
	}
	if ext != ".png" {
		t.Fatalf("validateImageUpload() extension = %q, want .png", ext)
	}
}

func TestValidateImageUploadRejectsDisguisedFile(t *testing.T) {
	if _, err := validateImageUpload(bytes.NewReader([]byte("not an image"))); err == nil {
		t.Fatal("validateImageUpload() accepted non-image content")
	}
}
